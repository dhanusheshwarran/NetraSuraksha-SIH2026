% ================================================================
% PORTAL 1 - QUALITY CONTROL + CLASSIFICATION
% ================================================================

function runPortal1(app, ui, ax_raw, ax_clahe, resLabel)

    % Reset previous scan state before a new attempt.
    app.UserData.PatientScanned = false;
    app.UserData.IsReferable = false;
    app.UserData.Img = [];
    app.UserData.Verdict = '';
    app.UserData.Confidence = 0;
    app.UserData.GradCAM = [];
    app.UserData.GradCAMArea = 0;

   [file, path] = uigetfile( ...
    {'*.png;*.jpg;*.jpeg;*.bmp', 'Retinal Images'}, ...
    'Select Retina Image');

if isequal(file, 0)
    figure(app);
    drawnow;
    return;
end

figure(app);
drawnow;

    try
        img = imread(fullfile(path, file));
    catch ME
        resLabel.Text = 'REJECTED: IMAGE COULD NOT BE READ';
        resLabel.FontColor = [1 0.2 0.2];
        warning('Image read failed: %s', ME.message);
        return;
    end

    % Make image RGB for a consistent model input.
    if ndims(img) == 2
        img = repmat(img, [1 1 3]);
    elseif size(img, 3) >= 3
        img = img(:, :, 1:3);
    else
        resLabel.Text = 'REJECTED: INVALID IMAGE FORMAT';
        resLabel.FontColor = [1 0.2 0.2];
        return;
    end

    imshow(img, 'Parent', ax_raw);
    axis(ax_raw, 'image');
    ax_raw.XTick = [];
    ax_raw.YTick = [];

    grayImg = rgb2gray(img);
    stdGray = imresize(grayImg, [512 512]);

    % ------------------------------------------------------------
    % IMAGE QUALITY GATE
    % ------------------------------------------------------------

    eyeMask = stdGray > 15;
    totalEyePixels = nnz(eyeMask);

    if totalEyePixels < 10000
        resLabel.Text = 'REJECTED: NO USABLE EYE DETECTED';
        resLabel.FontColor = [1 0.2 0.2];
        return;
    end

    % Strongly saturated reflection.
    glareMask = stdGray > 240;
    glareMask = bwareaopen(glareMask, 25);
    glareMask = glareMask & eyeMask;

    totalGlareRatio = nnz(glareMask) / totalEyePixels;

    % Largest connected glare component.
    cc = bwconncomp(glareMask);
    largestGlareRatio = 0;

    if cc.NumObjects > 0
        componentSizes = cellfun(@numel, cc.PixelIdxList);
        largestGlareRatio = max(componentSizes) / totalEyePixels;
    end

    % Broader bright artifact threshold for reflections that are not pure white.
    broadGlareMask = stdGray > 220;
    broadGlareMask = bwareaopen(broadGlareMask, 25);
    broadGlareMask = broadGlareMask & eyeMask;
    broadGlareRatio = nnz(broadGlareMask) / totalEyePixels;

    if totalGlareRatio > 0.020
        resLabel.Text = sprintf( ...
            'REJECTED: EXCESSIVE FLASH GLARE (%.2f%%)', ...
            totalGlareRatio * 100);
        resLabel.FontColor = [1 0.2 0.2];
        return;
    end

    if largestGlareRatio > 0.008
        resLabel.Text = sprintf( ...
            'REJECTED: LARGE FLASH REFLECTION (%.2f%%)', ...
            largestGlareRatio * 100);
        resLabel.FontColor = [1 0.2 0.2];
        return;
    end

    if broadGlareRatio > 0.040
        resLabel.Text = sprintf( ...
            'REJECTED: EXCESSIVE BRIGHT ARTIFACT (%.2f%%)', ...
            broadGlareRatio * 100);
        resLabel.FontColor = [1 0.2 0.2];
        return;
    end

    % ------------------------------------------------------------
    % FOCUS CHECK
    % ------------------------------------------------------------

    safeTissue = eyeMask & ...
        ~imdilate(glareMask, strel('disk', 5));

    lapImg = imfilter( ...
        double(stdGray), ...
        fspecial('laplacian', 0.2), ...
        'replicate');

    focusPixels = lapImg(safeTissue);

    if isempty(focusPixels)
        resLabel.Text = 'REJECTED: INSUFFICIENT USABLE TISSUE';
        resLabel.FontColor = [1 0.2 0.2];
        return;
    end

    focusScore = var(focusPixels);

    if focusScore < 15.0
        resLabel.Text = sprintf( ...
            'REJECTED: BLURRY IMAGE (Focus %.1f)', ...
            focusScore);
        resLabel.FontColor = [1 0.2 0.2];
        return;
    end

    % ------------------------------------------------------------
    % CLAHE VIEW
    % ------------------------------------------------------------

    claheEye = adapthisteq(grayImg, ...
        'NumTiles', [8 8], ...
        'ClipLimit', 0.02);

    imshow(claheEye, 'Parent', ax_clahe);
    axis(ax_clahe, 'image');
    ax_clahe.XTick = [];
    ax_clahe.YTick = [];

    app.UserData.GlareRatio = totalGlareRatio;
    app.UserData.LargestGlareRatio = largestGlareRatio;
    app.UserData.FocusScore = focusScore;

    resLabel.Text = 'QUALITY PASS - Processing trained AI model...';
    resLabel.FontColor = [0.3 0.7 1];
    drawnow;

    % ------------------------------------------------------------
    % LOAD TRAINED DAG NETWORK
    % ------------------------------------------------------------

    try
        modelFile = 'netrasuraksha_matlab_binary_95plus.mat';

        if ~isfile(modelFile)
            error('Model file "%s" was not found.', modelFile);
        end

        S = load(modelFile, 'trainedNet');
        trainedNet = S.trainedNet;

        if ~isa(trainedNet, 'DAGNetwork')
            error('Expected trainedNet to be a DAGNetwork. Found: %s', class(trainedNet));
        end

        imgResized = imresize(img, [224 224]);
        [pred, scores] = classify(trainedNet, imgResized);

        aiVerdict = string(pred);
        confidenceScore = max(scores(:)) * 100;

        % Keep the model available for Portal 3.
        app.UserData.XAINet = dag2dlnetwork(trainedNet);

        classNames = trainedNet.Layers(end).Classes;
        classIdx = find(strcmpi(string(classNames), aiVerdict), 1);

        if isempty(classIdx)
            error('Could not map AI prediction to the network class index.');
        end

        app.UserData.GradCAMClassIndex = classIdx;

    catch ME
        app.UserData.XAINet = [];
        resLabel.Text = 'ERROR: AI MODEL COULD NOT RUN';
        resLabel.FontColor = [1 0.4 0.2];
        warning('AI inference failed: %s', ME.message);
        return;
    end

    % ------------------------------------------------------------
    % STORE PATIENT RESULT
    % ------------------------------------------------------------

    app.UserData.Name = ui.name.Value;
    app.UserData.Age = num2str(ui.age.Value);
    app.UserData.Sugar = num2str(ui.sugar.Value);
    app.UserData.District = ui.district.Value;
    app.UserData.Phone = ui.phone.Value;
    app.UserData.Img = img;
    app.UserData.Verdict = aiVerdict;
    app.UserData.Confidence = confidenceScore;
    app.UserData.PatientScanned = true;

    v = strtrim(lower(aiVerdict));

    isHealthy = ...
        (v == "nonreferable") || ...
        (v == "non-referable") || ...
        (v == "normal") || ...
        (v == "no dr") || ...
        (v == "no_dr") || ...
        (v == "0");

    app.UserData.IsReferable = ~isHealthy;

    % ------------------------------------------------------------
    % ADD TO GOVERNMENT CENSUS REGISTRY
    % ------------------------------------------------------------

    newRecord = emptyScanRecord();
    newRecord.District = char(ui.district.Value);
    newRecord.Verdict = char(aiVerdict);
    newRecord.Confidence = confidenceScore;
    newRecord.IsReferable = app.UserData.IsReferable;

    registry = app.UserData.ScanRegistry;
    registry(end + 1) = newRecord;
    app.UserData.ScanRegistry = registry;

    % Refresh the government census immediately after every successful scan.
    if ~isempty(app.UserData.CensusTable)
        updateGovernmentPortal(app, ...
            app.UserData.CensusTable, ...
            app.UserData.TotalScannedLabel, ...
            app.UserData.ReferableLabel, ...
            app.UserData.NonReferableLabel, ...
            app.UserData.ReferralRateLabel, ...
            app.UserData.GovAx);

        updateSelectedRegion(app, ...
            app.UserData.RegionDrop, ...
            app.UserData.RegionDetailArea);
    end

    % ------------------------------------------------------------
    % FINAL STATUS
    % ------------------------------------------------------------

    if app.UserData.IsReferable
        resLabel.Text = sprintf( ...
            'QUALITY PASS | AI: %s | Confidence: %.1f%%', ...
            aiVerdict, confidenceScore);
        resLabel.FontColor = [1 0.6 0];
    else
        resLabel.Text = sprintf( ...
            'QUALITY PASS | AI: %s | Confidence: %.1f%%', ...
            aiVerdict, confidenceScore);
        resLabel.FontColor = [0 0.8 0];
    end

end

