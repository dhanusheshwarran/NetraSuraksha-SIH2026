            'Please visit an eye-care professional for confirmation.', ...
            '', ...
            sprintf('District: %s', app.UserData.District), ...
            sprintf('Phone: %s', app.UserData.Phone)};
    else
        msgArea.Value = { ...
            'NETRASURAKSHA UPDATE', ...
            '', ...
            sprintf('Dear %s,', app.UserData.Name), ...
            '', ...
            'Your AI screening result is classified as non-referable.', ...
            '', ...
            'Continue routine eye screening according to clinical guidance.'};
    end

end

% ================================================================
% PORTAL 3 - ACTUAL MODEL-BASED GRAD-CAM
% ================================================================

function runPortal3(app, ax_raw, ax_cam, repArea)

    if ~app.UserData.PatientScanned
        repArea.Value = { ...
            'ERROR: No valid patient scan found.', ...
            '', ...
            'Run Portal 1 first.'};
        return;
    end

    if isempty(app.UserData.XAINet)
        repArea.Value = { ...
            'ERROR: XAI network is not available.', ...
            '', ...
            'Run Portal 1 again so the trained model can be loaded.'};
        return;
    end

    img = app.UserData.Img;
    imshow(img, 'Parent', ax_raw);
    axis(ax_raw, 'image');
    ax_raw.XTick = [];
    ax_raw.YTick = [];

    try
        imgResized = imresize(img, [224 224]);

        % --------------------------------------------------------
        % TRUE GRAD-CAM FROM THE TRAINED NETWORK
        % --------------------------------------------------------
        scoreMap = gradCAM( ...
            app.UserData.XAINet, ...
            imgResized, ...
            app.UserData.GradCAMClassIndex, ...
            'FeatureLayer', app.UserData.GradCAMFeatureLayer);

        scoreMap = squeeze(scoreMap);
        scoreMap = mat2gray(scoreMap);
        scoreMap = imresize(scoreMap, [size(img,1) size(img,2)]);

        app.UserData.GradCAM = scoreMap;

        % High-attention region = thresholded Grad-CAM, not lesion segmentation.
        attentionMask = scoreMap >= 0.60;
        attentionMask = bwareaopen(attentionMask, 50);

        usableMask = rgb2gray(img) > 15;
        attentionMask = attentionMask & usableMask;

        if nnz(usableMask) > 0
            gradCAMArea = nnz(attentionMask) / nnz(usableMask) * 100;
        else
            gradCAMArea = 0;
        end

        app.UserData.GradCAMArea = gradCAMArea;

        % --------------------------------------------------------
        % DISPLAY GRAD-CAM OVERLAY
        % --------------------------------------------------------
        imshow(img, 'Parent', ax_cam);
        axis(ax_cam, 'image');
        ax_cam.XTick = [];
        ax_cam.YTick = [];
        hold(ax_cam, 'on');

        heatHandle = imagesc(ax_cam, scoreMap);
        colormap(ax_cam, jet(256));
        heatHandle.AlphaData = 0.50 * scoreMap;

        % Visual boundary of the strongest attention area.
        if any(attentionMask(:))
            contour(ax_cam, attentionMask, [1 1], ...
                'Color', 'w', 'LineWidth', 1.5);
        end

        colorbar(ax_cam);
        caxis(ax_cam, [0 1]);
        title(ax_cam, 'Grad-CAM: Stronger model influence', 'Color', 'w');
        hold(ax_cam, 'off');

        % --------------------------------------------------------
        % DOCTOR-FACING EXPLANATION
        % --------------------------------------------------------

        if app.UserData.IsReferable
            actionText = ...
                'Recommended next step: professional ophthalmic evaluation.';
        else
            actionText = ...
                'Recommended next step: routine follow-up according to clinical guidance.';
        end

        if app.UserData.Confidence >= 80
            confidenceText = 'High model confidence.';
        elseif app.UserData.Confidence >= 60
            confidenceText = 'Moderate model confidence.';
        else
            confidenceText = 'Lower model confidence; review the image carefully.';
        end

        reportLines = { ...
            sprintf('PATIENT: %s', app.UserData.Name), ...
            sprintf('AGE: %s | RBS: %s', app.UserData.Age, app.UserData.Sugar), ...
            sprintf('REGION: %s', app.UserData.District), ...
            '', ...
            sprintf('AI DIAGNOSIS: %s', upper(app.UserData.Verdict)), ...
            sprintf('MODEL CONFIDENCE: %.1f%%', app.UserData.Confidence), ...
            confidenceText, ...
            '', ...
            '--- AI EXPLANATION ---', ...
            'The trained classifier produced the diagnosis shown above.', ...
            'Grad-CAM identifies image regions that contributed strongly', ...
            'to the predicted class score.', ...
            '', ...
            sprintf('HIGHLIGHTED ATTENTION AREA: %.2f%%', gradCAMArea), ...
            '', ...
            '--- HOW TO READ THE MAP ---', ...
            'Red / yellow = stronger model contribution.', ...
            'Blue / dark = weaker model contribution.', ...
            '', ...
            '--- IMPORTANT XAI NOTE ---', ...
            'This is a model-attention map, not a pixel-perfect lesion', ...
            'segmentation. It shows where the classifier was influenced.', ...
            '', ...
            '--- ACTION ---', ...
            actionText};

        repArea.Value = reportLines;

    catch ME
        app.UserData.GradCAM = [];
        app.UserData.GradCAMArea = 0;

        repArea.Value = { ...
            'ERROR: GRAD-CAM COULD NOT BE GENERATED.', ...
            '', ...
            'The classification result remains available in Portal 1.', ...
            '', ...
            sprintf('Technical message: %s', ME.message)};

        warning('Grad-CAM failed: %s', ME.message);
    end

end

% ================================================================
% GOVERNMENT PORTAL UPDATE
% ================================================================

function updateGovernmentPortal(app, censusTable, ...
    totalScannedLabel, referableLabel, nonReferableLabel, ...
    referralRateLabel, govAx)

    districts = {'Coimbatore', 'Madurai', 'Chennai', 'Salem', 'Trichy'};

    scanned = zeros(numel(districts), 1);
    referable = zeros(numel(districts), 1);
    nonReferable = zeros(numel(districts), 1);

    registry = app.UserData.ScanRegistry;

    for i = 1:numel(districts)
        districtMask = strcmpi( ...
            {registry.District}, districts{i});

        districtRecords = registry(districtMask);

        scanned(i) = numel(districtRecords);

        if ~isempty(districtRecords)
            referable(i) = sum([districtRecords.IsReferable]);
            nonReferable(i) = scanned(i) - referable(i);
        end
    end

    totalScanned = sum(scanned);
    totalReferable = sum(referable);
    totalNonReferable = sum(nonReferable);

    if totalScanned > 0
        overallReferralRate = totalReferable / totalScanned * 100;
    else
        overallReferralRate = 0;
    end

    totalScannedLabel.Text = num2str(totalScanned);
    referableLabel.Text = num2str(totalReferable);
    nonReferableLabel.Text = num2str(totalNonReferable);
    referralRateLabel.Text = sprintf('%.1f%%', overallReferralRate);

    % Table data.
    rates = zeros(numel(districts), 1);
    for i = 1:numel(districts)
        if scanned(i) > 0
            rates(i) = referable(i) / scanned(i) * 100;
        end
    end

    tableData = cell(numel(districts), 5);

    for i = 1:numel(districts)
        tableData{i,1} = districts{i};
        tableData{i,2} = scanned(i);
        tableData{i,3} = referable(i);
        tableData{i,4} = nonReferable(i);
        tableData{i,5} = sprintf('%.1f%%', rates(i));
    end

    censusTable.Data = tableData;

    % ------------------------------------------------------------
    % REGIONAL HEAT MAP
    % ------------------------------------------------------------

    lats = [ ...
        11.0168 ... % Coimbatore
        9.9252  ... % Madurai
        13.0827 ... % Chennai
        11.6643 ... % Salem
        10.7905];   % Trichy

    lons = [ ...
        76.9558 ...
        78.1198 ...
        80.2707 ...
        78.1460 ...
        78.7047];

    cla(govAx);
    hold(govAx, 'on');

    % Approximate Tamil Nadu outline for the demo dashboard.
    tn_lon = [76.0 77.0 78.0 79.5 80.3 79.8 79.0 78.0 77.0 76.0];
    tn_lat = [11.5 13.0 13.5 13.5 13.0 10.5 9.0 8.0 9.5 11.5];

    fill(govAx, tn_lon, tn_lat, [0.12 0.14 0.18], ...
        'EdgeColor', [0 0.7 1], ...
        'LineWidth', 1.5);

    % Marker size reflects screening volume; color reflects referral rate.
    markerSizes = 160 + 70 .* sqrt(double(scanned));

    scatter(govAx, lons, lats, markerSizes, rates, ...
        'filled', ...
        'MarkerEdgeColor', 'w', ...
        'LineWidth', 0.8);

    colormap(govAx, hot(256));
    caxis(govAx, [0 max(30, max(rates) + 1)]);
    cb = colorbar(govAx);
    cb.Color = 'w';
    cb.Label.String = 'Referral rate (%)';
    cb.Label.Color = 'w';

    text(govAx, lons, lats - 0.22, districts, ...
        'Color', 'w', ...
        'HorizontalAlignment', 'center', ...
        'FontSize', 10, ...
        'FontWeight', 'bold');

    % Add screening count above each location.
    for i = 1:numel(districts)
        text(govAx, lons(i), lats(i) + 0.22, ...
            sprintf('N=%d | %.1f%%', scanned(i), rates(i)), ...
            'Color', [0.9 0.9 0.9], ...
            'HorizontalAlignment', 'center', ...
            'FontSize', 8);
    end

    govAx.XLim = [75.0 81.5];
    govAx.YLim = [7.5 14.0];
    govAx.XTick = [];
    govAx.YTick = [];
    axis(govAx, 'equal');

    hold(govAx, 'off');

end

% ================================================================
% SELECTED REGION DETAILS
% ================================================================

function updateSelectedRegion(app, regionDrop, regionDetailArea)

    selectedRegion = char(regionDrop.Value);
    registry = app.UserData.ScanRegistry;

    mask = strcmpi({registry.District}, selectedRegion);
    records = registry(mask);

    scanned = numel(records);

    if scanned > 0
        referable = sum([records.IsReferable]);
    else
        referable = 0;
    end

    nonReferable = scanned - referable;

    if scanned > 0
        referralRate = referable / scanned * 100;
    else
        referralRate = 0;
    end

    severity = getSeverityBand(referralRate);

    regionDetailArea.Value = { ...
        sprintf('REGION: %s', selectedRegion), ...
        '', ...
        sprintf('Total scanned: %d', scanned), ...
        sprintf('Referable: %d', referable), ...
        sprintf('Non-referable: %d', nonReferable), ...
        sprintf('Referral rate: %.1f%%', referralRate), ...
        '', ...
        sprintf('SEVERITY BAND: %s', severity), ...
        '', ...
        'Interpretation:', ...
        'This demo heat map summarizes the proportion of', ...
        'successfully screened cases classified as referable.', ...
        '', ...
        'These severity bands are demonstration thresholds,', ...
        'not clinical or epidemiological standards.'};

end

% ================================================================
% RESET CENSUS
% ================================================================

function resetCensus(app, censusTable, totalScannedLabel, ...
    referableLabel, nonReferableLabel, referralRateLabel, ...
    govAx, regionDetailArea, regionDrop)

    answer = uiconfirm(app, ...
        'Clear all screening counts from this session?', ...
        'Reset Government Census', ...
        'Options', {'Reset', 'Cancel'}, ...
        'DefaultOption', 2, ...
        'CancelOption', 2);

    if strcmp(answer, 'Reset')
        app.UserData.ScanRegistry = repmat(emptyScanRecord(), 0, 1);

        updateGovernmentPortal(app, censusTable, totalScannedLabel, ...
            referableLabel, nonReferableLabel, referralRateLabel, govAx);

        regionDetailArea.Value = {'Select a region and click VIEW REGION.'};
        regionDrop.Value = 'Coimbatore';
    end

end

% ================================================================
% SEVERITY BAND HELPER
% ================================================================

function severity = getSeverityBand(referralRate)

    if referralRate < 10
        severity = 'LOW';
    elseif referralRate < 20
        severity = 'MODERATE';
    elseif referralRate < 30
        severity = 'HIGH';
    else
        severity = 'VERY HIGH';
    end

end

% ================================================================
% EMPTY REGISTRY RECORD
% ================================================================

function record = emptyScanRecord()

    record = struct( ...
        'District', '', ...
        'Verdict', '', ...
        'Confidence', 0, ...
        'IsReferable', false);

end
